def ellipsoid_region(P, c):
    """Предикат «x внутри сертифицированной области притяжения x^T P x <= c».

    P -- решение уравнения Риккати, c -- уровень из `wpend.lqr.certified_level`:
    наибольший, при котором весь эллипсоид лежит в {V̇ < 0}. Внутри этого
    множества сходимость ЛКР на НЕЛИНЕЙНОЙ системе доказана (Khalil, гл. 8.2),
    а не измерена. Цена -- консервативность: настоящий бассейн заметно шире.

    Проверка идёт по ПОЛНОМУ состоянию, включая колесо: c* сертифицирован для
    4-мерного эллипсоида, и выбрасывать из проверки theta/dtheta значит потерять
    ровно ту гарантию, ради которой этот вариант и берут.
    """
    P = np.asarray(P, dtype=float)
    c = float(c)

    def inside(x):
        x = np.asarray(x, dtype=float)
        return np.einsum("...i,ij,...j->...", x, P, x) <= c

    return inside


def _nearest_index(grid, values):
    """Индекс ближайшего узла возрастающей сетки для каждого значения."""
    j = np.clip(np.searchsorted(grid, values), 1, len(grid) - 1)
    return np.where(values - grid[j - 1] <= grid[j] - values, j - 1, j)


def grid_region(mask, psis, dpsis, i_psi=0, i_dpsi=2):
    """Предикат «клетка карты (psi, dpsi) помечена как удержанная».

    `mask` -- булева матрица формы (len(dpsis), len(psis)); порядок осей
    тот же, что у `wpend.viz.grid.GridSpec`: строка -- dpsi, столбец -- psi.
    Обычно это результат прогона сетки под чистым ЛКР: `classify(...) == HELD`.

    Это измеренный бассейн, а не доказанный: клетка означает «за горизонт
    прогона корпус не упал», и между узлами ничего не гарантировано. Зато он
    заметно шире эллипсоида -- в этом и смысл сравнения.

    Читает только (psi, dpsi). Для вопроса «упадёт ли» это не потеря
    общности: ускорения колёсного маятника не зависят ни от theta, ни от dtheta
    (Key_Formulas §1.4), поэтому карта и строится в этой плоскости. Но для
    вопроса «сойдётся ли ЛКР к нулю ПОЛНОСТЬЮ» -- потеря: колесо, укатившееся
    далеко, из проверки выпадает, и регулятор может переключиться раньше, чем
    имеет право. Именно это и надо увидеть в сравнении.
    """
    mask = np.asarray(mask, dtype=bool)
    psis = np.asarray(psis, dtype=float)
    dpsis = np.asarray(dpsis, dtype=float)
    if mask.shape != (dpsis.size, psis.size):
        raise ValueError(f"mask должна быть формы {(dpsis.size, psis.size)}, "
                         f"а не {mask.shape}")

    def inside(x):
        x = np.asarray(x, dtype=float)
        th, dth = x[..., i_psi], x[..., i_dpsi]
        on_grid = ((th >= psis[0]) & (th <= psis[-1])
                   & (dth >= dpsis[0]) & (dth <= dpsis[-1]))
        ix = _nearest_index(psis, np.clip(th, psis[0], psis[-1]))
        iy = _nearest_index(dpsis, np.clip(dth, dpsis[0], dpsis[-1]))
        return mask[iy, ix] & on_grid

    return inside


def psi_band_region(eps, i_psi=0):
    """Предикат «корпус в eps-окрестности вертикали»: |psi| < eps.

    Самый грубый ответ на вопрос «когда отдавать управление ЛКР» -- и
    сознательно грубый. Ни dpsi, ни колесо в проверку не входят.

    Почему dpsi можно не проверять. Реле едет по сепаратрисе, а на ней
    при psi -> 0 и dpsi -> 0 (из H(ψ, ψ̇; ∓u_max) = γD, Key_Formulas §3:
    ψ̇² ~ |ψ| вблизи нуля). Значит первый вход в полосу обычно происходит уже с
    малой скоростью. Обычно, но не всегда: траектория выше сепаратрисы
    пролетает psi = 0 на скорости, и полоса её пропустит. Замер
    (PROPOSALS.md A26): при u_max = 10 |dpsi| в момент передачи доходит до 1.8,
    а ЛКР с мягким колесом ловит и эти состояния.

    Сертификата у такой пары НЕТ: полоса не множество уровня V и не
    инвариантна (ЛКР может вывести наклон обратно за eps, поэтому переключение
    имеет смысл только с защёлкой, `latch=True`). Это измеренный, а не
    доказанный критерий, как `grid_region`.

    eps -- настраиваемый параметр, в радианах.
    """
    eps = float(eps)
    if not eps > 0.0:
        raise ValueError(f"eps должен быть > 0, а не {eps}")

    def inside(x):
        x = np.asarray(x, dtype=float)
        return np.abs(x[..., i_psi]) < eps

    return inside


#: Какую энергию качать и по какой следить. Пара (величина, её мощность)
#: обязана быть согласованной: закон ставит знак так, чтобы dE/dt имела знак
#: промаха, и подмена одной половины пары ломает не точность, а гарантию.
#:   "total" -- полная энергия машины,  dE/dt     = u (dpsi - dtheta);
#:   "tilt"  -- энергия приведённой динамики наклона (Key_Formulas §4.2-4.3),
#:              dE_psi/dt = u b(psi) dpsi / gamma -- БЕЗ скорости колеса.
ENERGY_TARGETS = ("total", "tilt")


def _energy_pair(system, target):
    """(величина, её производная по времени при управлении u) для цели."""
    if target not in ENERGY_TARGETS:
        raise ValueError(f"energy должно быть одним из {ENERGY_TARGETS}, а не {target!r}")
    if target == "total":
        return system.energy, system.power
    return system.tilt_energy, system.tilt_power


def energy_band_region(system, eps_E, energy="total"):
    """Предикат «энергии ровно столько, сколько наверху»: |E(x) - E*| < eps_E.

    Решение Глеба 22.09 (ER-018): переключение энергетической схемы привязано
    к УРОВНЮ энергии, а не только к наклону. Сам по себе этот предикат целью
    не является и в одиночку не используется -- см. ниже, почему.

    Что он проверяет и чего не проверяет. `E` -- полная энергия машины
    (Key_Formulas §4), `E* = D` -- её значение в верхнем положении при нулевых
    скоростях. Разложение §4.2

        E = H(psi, dpsi; 0) / gamma + p_theta^2 / (2 gamma)

    точное, и из него видно главное: множество `E = E*` ТРЁХМЕРНО, и почти всё
    оно лежит далеко от вертикали. При `p_theta != 0` тот же уровень энергии
    набирается при меньшей `H`, то есть наклону досталось МЕНЬШЕ, чем нужно
    для подъёма. Поэтому «энергия на уровне» -- условие НЕОБХОДИМОЕ, но не
    достаточное, и в паре с ним всегда должен стоять второй предикат,
    отвечающий за «и корпус при этом наверху» (`psi_band_region` или
    `ellipsoid_region`), сцепленный через `all_regions`.

    Сертификата у такой пары нет -- как и у полосы по psi (A26): множество
    `|E - E*| < eps_E` не есть множество уровня функции Ляпунова замкнутой
    системы и не инвариантно. Значит только с защёлкой (`latch=True`).

    eps_E -- в тех же единицах, что энергия (Дж). Осмысленный масштаб:
    `D (1 - cos d)` -- энергия, которой не хватает корпусу, отклонённому на
    `d` от вертикали. При `D = 98` и `d = 0.1` рад это 0.49.

    energy -- "total" (полная энергия машины) или "tilt" (энергия приведённой
    динамики наклона, `tilt_energy`). Уровень цели `E* = D` у обеих ОДИН И ТОТ
    ЖЕ, отличается только то, что считается энергией: «сколько её в машине»
    против «сколько её досталось корпусу». Оговорка выше про `p_theta != 0`
    относится к "total"; у "tilt" вклад колеса вычтен по построению, поэтому
    там `E_psi = D` значит ровно «наклону энергии хватает».

    system -- модель, умеющая нужную пару и `E_upright` (`WheeledPendulum`).
    """
    eps_E = float(eps_E)
    if not eps_E > 0.0:
        raise ValueError(f"eps_E должен быть > 0, а не {eps_E}")
    if not hasattr(system, "E_upright"):
        raise TypeError("energy_band_region: модели нужен E_upright")
    value, _ = _energy_pair(system, energy)
    E_star = float(system.E_upright)

    def inside(x):
        return np.abs(value(np.asarray(x, dtype=float)) - E_star) < eps_E

    return inside


def all_regions(*regions):
    """Конъюнкция предикатов: внутри там, где внутри у КАЖДОГО.

    Регион -- аргумент-функция, а не класс (A11), поэтому и «И» между двумя
    критериями -- функция, а не флаг внутри регулятора. Альтернатива (завести
    у `BangBangLQRController` второй `region` и ветку) означала бы, что
    условие передачи написано в двух местах: в предикате и в регуляторе.

    Соглашение о пачках держится само: каждый предикат возвращает (M,) bool,
    и `&` поэлементно.
    """
    if not regions:
        raise ValueError("all_regions: нужен хотя бы один предикат")

    def inside(x):
        out = np.asarray(regions[0](x), dtype=bool)
        for region in regions[1:]:
            out = out & np.asarray(region(x), dtype=bool)
        return out

    return inside


#: Коды фаз `BangBangLQRController`, в порядке, в котором он их проходит.
#: Живут рядом с регулятором, а не в окне: фаза -- его собственное состояние,
#: и два места, где написано «единица значит ЛКР», разошлись бы молча.
PHASE_BANG, PHASE_LQR, PHASE_FINAL = 0, 1, 2


class BangBangLQRController(Controller):
    """Релейное управление до входа в регион, ЛКР -- внутри.

    Идея. ЛКР доказуемо работает только вблизи верхнего положения: он построен
    по линеаризации, и на большом наклоне выброшенные нелинейности перевешивают.
    Релейное же управление u = ±u_max не претендует на точность -- оно просто
    выжимает из мотора всё и приводит состояние туда, где ЛКР законен. Отсюда
    двухфазная схема: сначала догнать регион, потом отдать управление ЛКР.

    Закон переключения релейной фазы -- ТОЧНАЯ сепаратриса, а не подгонка
    -------------------------------------------------------------------------
    Наклон колёсного маятника живёт своей жизнью: theta циклична, поэтому
    (Key_Formulas §1.3-1.4)

        Δ(ψ) ψ̈ = b(ψ) u + γ D sin ψ − β² sin ψ cos ψ ψ̇² ,

    и при ПОСТОЯННОМ u сохраняется первый интеграл (§3)

        H(ψ, ψ̇; u) = ½ Δ(ψ) ψ̇² − u (γ ψ + β sin ψ) + γ D cos ψ .

    Значит фазовые кривые при u = const -- в точности линии уровня H, и
    траекторию, приходящую в верхнее положение, можно выписать, а не подобрать:

      * при ψ̇ > 0 корпус уезжает вперёд, тормозим моментом u = −u_max, и
        нужная кривая -- ветвь уровня H(·; −u_max) = H(0,0) = γ D;
      * при ψ̇ < 0 -- зеркально, u = +u_max на уровне H(·; +u_max) = γ D.

    Обозначив d = sign ψ̇ (а при ψ̇ = 0 -- sign ψ), обе ветви складываются в одну
    переключающую функцию

        σ(ψ, ψ̇) = d · [ H(ψ, ψ̇; −u_max·d) − γ D ] ,      u = −u_max · sign σ.

    Читается так: σ > 0 -- «энергии больше, чем на тормозной кривой, ведущей в
    ноль», надо тормозить; σ < 0 -- «меньше», надо разгоняться к нулю.

    Проверка знака в пределе двойного интегратора (β = 0, D = 0, то есть
    ψ̈ = u/α): при ψ̇ > 0 получается σ = γ(½ α ψ̇² + u_max ψ) -- это, с точностью
    до положительного множителя, классическая переключающая функция
    ψ + α ψ̇|ψ̇| / (2 u_max) с u = −u_max sign(·).

    Чего эта формула НЕ обещает
    ---------------------------
    * Оптимальность «одного переключения» -- свойство участка внутри
      восстановимого множества. Дальше, за седлом u = −u_max (уровень K(u_max),
      см. `src/recoverable.py`), спасения нет вообще, и формула вырождается в
      «тормозить изо всех сил» -- лучшее из доступного, но не возврат.
    * Колесо. Релейная фаза считает только наклон; theta за это время уезжает, и
      возвращает его уже ЛКР. Если фаза длинная, состояние может не попасть в
      4-мерный эллипсоид именно из-за theta -- это видно в `examples/bangbang_lqr.py`.
    * На самой кривой σ = 0 управление дребезжит с частотой шага интегратора.
      Это неустранимое свойство релейного закона и одна из причин передавать
      управление ЛКР, а не досиживать до нуля на реле.

    Параметры
    ---------
    K : (n_action, n_state)
        Матрица ЛКР. Синтез -- `wpend.lqr.lqr` или числа снаружи.
    u_max : float
        Модуль релейного момента. Это НЕ дубликат `System.u_bounds`: система
        обрезает то, что регулятор просит, а здесь записано, на что регулятор
        рассчитывает. Если поставить больше системного предела, релейная фаза
        будет считать сепаратрису для мотора, которого нет, и промахнётся;
        `Trajectory.u` при этом честно покажет обрезанное значение.
    region : callable
        Предикат x -> bool (или (M,) bool для пачки). См. `ellipsoid_region`
        и `grid_region`.
    system : WheeledPendulum
        Нужен ровно ради `first_integral` и параметров γ, D -- то есть ради
        формулы сепаратрисы. Никакого состояния из системы не читается.
    wheel_ref : bool
        False (по умолчанию) -- ЛКР гонит колесо в theta = 0, а регион
        проверяется по полному состоянию. True -- ПРИВЯЗКА К КОЛЕСУ (§B8):
        целью становится не theta = 0, а то положение колеса, в котором
        произошла передача.

        Почему это законно, а не подгонка. Координата theta циклична: правая
        часть f от неё не зависит вовсе (Key_Formulas §1.4). Значит для
        e = x - (0, theta_ref, 0, 0) выполняется ė = f(e, u) с той же самой
        функцией f -- сдвиг вдоль theta не меняет векторное поле. Поэтому
        сертификат «V̇ < 0 внутри x^T P x <= c*» переносится на e ДОСЛОВНО,
        без нового доказательства (Khalil, гл. 8.2 + инвариантность поля).

        Что меняется на практике: до передачи регион проверяется по состоянию
        с обнулённой theta -- то есть задаётся вопрос «поместились бы мы в
        эллипсоид, если объявить колесо стоящим там, где оно есть». В момент
        передачи theta_ref защёлкивается, и дальше ЛКР работает как u = -K e,
        то есть выпрямляет корпус и останавливает колесо ТАМ, ГДЕ ОНО
        ОКАЗАЛОСЬ. Цель прогона меняется с «приехать в ноль» на
        «остановиться где стоишь» -- это надо признавать вслух.

        Скорость колеса dtheta при этом из проверки НЕ уходит: она не циклична,
        и вклад P[3,3] dtheta^2 остаётся. Привязка снимает вклад theta, но не
        вклад dtheta -- см. замер в PROPOSALS.md §B8.
    latch : bool
        True (по умолчанию) -- вошёл в регион и остался в ЛКР до `reset()`.
        Сертифицированный эллипсоид инвариантен (внутри V̇ < 0, значит V
        убывает и наружу состояние не выйдет), поэтому защёлка не отнимает
        корректности, но снимает дребезг на границе от численного шума.
        False -- регион проверяется заново каждый шаг.

    K_final, final_region : необязательная ТРЕТЬЯ фаза (A27)
        None, None (по умолчанию) -- двухфазная схема, поведение побитово
        прежнее. Иначе: после передачи на K регулятор ждёт, пока состояние
        войдёт в final_region, и с этого шага навсегда (до `reset()`) подаёт
        u = -K_final x.

        Зачем. Вторая фаза отвечает за то, чтобы НЕ УРОНИТЬ: мягкий ЛКР
        (пониженные гейны по theta, dtheta) ловит состояния, которые жёсткий
        роняет, но возвращает колесо медленно. Третья фаза -- за то, чтобы
        ДОВЕСТИ: когда мягкий уже привёл состояние туда, где жёсткий
        доказуемо работает, отдаём управление жёсткому.

        Какой регион законен. Эллипсоид x^T P_final x <= c* из
        `certified_level` для ТОЙ ЖЕ пары (K_final, P_final) и того же u_max:
        внутри него V̇ < 0 при обрезанном управлении, множество инвариантно,
        и сходимость -K_final x доказана (Khalil, гл. 8.2). Поэтому здесь, в
        отличие от полосы по psi, пара «критерий + регулятор» честная.
        Проверка идёт по полному состоянию: колесо в сертификате участвует.

        При wheel_ref=True третья фаза видит то же состояние, что вторая,
        -- x с вычтенным theta_ref: theta циклична, сертификат переносится.

        Третья фаза следует ТОЛЬКО за второй: попадание в final_region
        во время релейной фазы не считается. Иначе при широком c* реле
        отдавало бы управление жёсткому ЛКР в обход мягкого, а это ровно та
        передача, которая по замеру A26 теряет клетки.

    Память (флаги защёлок) живёт в регуляторе -- правило 2 архитектуры; для
    пачки (M, n) это векторы из M флагов, независимых по строкам. `reset()`
    вызывается `rollout`-ом один раз перед прогоном.
    """

    def __init__(self, K, u_max, region, system, *, i_psi=0, i_theta=1,
                 i_dpsi=2, latch=True, wheel_ref=False,
                 K_final=None, final_region=None):
        self.K = np.atleast_2d(np.asarray(K, dtype=float))
        self.u_max = float(u_max)
        self.region = region
        self.system = system
        self.i_psi = int(i_psi)
        self.i_theta = int(i_theta)
        self.i_dpsi = int(i_dpsi)
        self.latch = bool(latch)
        self.wheel_ref = bool(wheel_ref)
        if (K_final is None) != (final_region is None):
            raise ValueError("K_final и final_region задаются только вместе: "
                             "критерий и регулятор после него -- одна пара")
        self.K_final = (None if K_final is None
                        else np.atleast_2d(np.asarray(K_final, dtype=float)))
        self.final_region = final_region
        # H(0, 0; u) = γ D при любом u -- уровень, на котором лежит кривая,
        # приходящая в верхнее положение.
        self.H_upright = float(system.first_integral(
            np.zeros(system.n_state), 0.0))
        self._engaged = None
        self._theta_ref = None
        self._final = None
        self._phase = None

    def reset(self) -> None:
        self._engaged = None
        self._theta_ref = None
        self._final = None
        self._phase = None

    def phase(self):
        """В какой фазе посчитано ПОСЛЕДНЕЕ управление: PHASE_BANG (реле),
        PHASE_LQR (ЛКР после передачи) или PHASE_FINAL (третья фаза, A27).
        Форма -- как у пачки: скаляр для одного состояния, (M,) для M строк.
        None, пока `act` ни разу не вызван после `reset`.

        Это не новое решение, а ЧТЕНИЕ уже принятого. Флаги защёлок -- память
        регулятора (правило 2 архитектуры), и на вопрос «в какой фазе он был
        на этом шаге» отвечает он сам. Восстанавливать фазу снаружи, повторяя
        предикаты и защёлку, значило бы завести второй источник правды,
        который разойдётся с первым молча -- при смене региона, цены или
        порядка проверок. Дорожка фаз в окне (`wpend.viz.phases`) поэтому
        прогоняет сам регулятор по записанной оценке и спрашивает его здесь.
        """
        return self._phase

    def switching_function(self, x_hat):
        """σ(ψ, ψ̇) из докстринга класса. Вынесено отдельно ради теста:
        вдоль траектории с постоянным u = −u_max, стартующей с σ = 0,
        величина σ обязана оставаться нулём -- это сохранение H, а не
        сравнение с прошлым прогоном."""
        x = np.asarray(x_hat, dtype=float)
        psi, dpsi = x[..., self.i_psi], x[..., self.i_dpsi]
        # При ψ̇ = 0 направление задаёт сам наклон: из (ψ > 0, ψ̇ = 0) надо
        # толкать назад, а не «в сторону, куда летим», -- лететь ещё некуда.
        d = np.where(dpsi != 0.0, np.sign(dpsi), np.sign(psi))
        return d * (self.system.first_integral(x, -self.u_max * d)
                    - self.H_upright)

    def first_phase_action(self, x):
        """Управление ПЕРВОЙ фазы -- то, что подаётся, пока регион не достигнут.

        Вынесено отдельным методом ровно ради ER-018: `EnergyBangBangController`
        меняет ТОЛЬКО этот закон, а регион, защёлки, привязку колеса, третью
        фазу и `phase()` наследует как есть.  Иначе сравнение двух релейных
        законов пришлось бы делать двумя копиями одной машинерии, и любое
        расхождение между копиями читалось бы как разница законов.

        σ >= 0 -> тормозим.  Равенство попадает в ту же ветвь сознательно:
        sign(0) = 0 дало бы u = 0, то есть «отпустить мотор» ровно на той
        кривой, вдоль которой и надо ехать.
        """
        return np.where(self.switching_function(x) >= 0.0,
                        -self.u_max, self.u_max)[..., None]

    def _probe(self, x):
        """Состояние, по которому проверяется регион.

        При привязке к колесу вопрос звучит как «поместились бы мы, если
        объявить колесо стоящим там, где оно есть», поэтому theta обнуляется.
        Скорость колеса не трогаем: она не циклична и из проверки не уходит.
        """
        if not self.wheel_ref:
            return x
        probe = np.array(x, dtype=float, copy=True)
        probe[..., self.i_theta] = 0.0
        return probe

    def _error(self, x):
        """Состояние, которое видит ЛКР: x либо x - (0, theta_ref, 0, 0)."""
        if not self.wheel_ref:
            return x
        err = np.array(x, dtype=float, copy=True)
        err[..., self.i_theta] = x[..., self.i_theta] - self._theta_ref
        return err

    def act(self, t: float, x_hat: np.ndarray) -> np.ndarray:
        x = np.asarray(x_hat, dtype=float)

        inside = np.asarray(self.region(self._probe(x)), dtype=bool)
        if self._engaged is None or self._engaged.shape != inside.shape:
            self._engaged = np.zeros(inside.shape, dtype=bool)
            self._theta_ref = np.zeros(inside.shape, dtype=float)
        # theta_ref защёлкивается на переднем фронте: цель фиксируется один раз,
        # в момент передачи, и дальше не уползает вслед за колесом.
        newly = inside & ~self._engaged
        self._theta_ref = np.where(newly, x[..., self.i_theta], self._theta_ref)
        self._engaged = (self._engaged | inside) if self.latch else inside

        u_bang = self.first_phase_action(x)
        err = self._error(x)
        u_lqr = -err @ self.K.T
        u = np.where(self._engaged[..., None], u_lqr, u_bang)
        if self.K_final is None:
            self._phase = np.where(self._engaged, PHASE_LQR, PHASE_BANG)
            return u

        # Третья фаза: защёлка, взводимая только поверх второй. Проверяется
        # после обновления _engaged, поэтому вход во вторую и третью на одном
        # шаге законен -- состояние уже внутри сертифицированного эллипсоида.
        if self._final is None or self._final.shape != inside.shape:
            self._final = np.zeros(inside.shape, dtype=bool)
        in_final = np.asarray(self.final_region(err), dtype=bool) & self._engaged
        self._final = self._final | in_final
        self._phase = np.where(self._final, PHASE_FINAL,
                               np.where(self._engaged, PHASE_LQR, PHASE_BANG))
        return np.where(self._final[..., None], -err @ self.K_final.T, u)


class EnergyBangBangController(BangBangLQRController):
    """Накачка ПОЛНОЙ ЭНЕРГИИ до уровня верхнего положения, затем ЛКР (ER-018).

    Решение Глеба 22.09.2026: первая фаза следит не за сепаратрисой, а за одним
    числом -- полной механической энергией машины, -- и поднимает его до
    уровня E* = D (корпус в вертикали, обе скорости нулевые).  Всё, что идёт
    после первой фазы, -- регион передачи, защёлка, привязка колеса, третья
    фаза, `phase()` -- унаследовано от `BangBangLQRController` без единой
    правки: сравнение двух законов обязано менять РОВНО ОДНУ вещь, иначе оно
    меряет разницу реализаций, а не разницу законов.

    Закон
    -----
    Полная энергия и уровень цели (Key_Formulas §4, `WheeledPendulum.energy`):

        E(x)  = ½ α ψ̇² + β cos ψ · ψ̇ θ̇ + ½ γ θ̇² + D cos ψ ,     E* = D .

    Мотор стоит МЕЖДУ корпусом и колесом (Q_ψ = u, Q_θ = −u), поэтому вводимая
    мощность считается по ОТНОСИТЕЛЬНОЙ скорости (§4.1):

        Ė = u · (ψ̇ − θ̇) .

    Отсюда закон накачки: знак момента выбирается так, чтобы энергия шла в
    сторону цели,

        v = ψ̇ − θ̇ ,   g = E* − E(x) ,   u = u_max · sign(g) · sign(v) .

    Функция Ляпунова -- квадрат промаха по энергии W = ½ (E − E*)²:

        Ẇ = (E − E*) Ė = − u_max · |g · v| ≤ 0 ,

    то есть промах по энергии не растёт НИКОГДА, при любом наклоне и любом
    состоянии колеса.  Это и есть главное отличие от сепаратрисного закона:
    там гарантия привязана к модели целиком (в σ входят Δ(ψ), β, γ, D), здесь
    -- к одному скалярному балансу.

    Вырождение v = 0 и почему оно не «sign(0) = 0»
    ----------------------------------------------
    При ψ̇ = θ̇ мотор не вводит мощности ВОВСЕ, каким бы ни был момент, и
    произведение g·v равно нулю.  Формально знак не определён; буквальное
    sign(0) = 0 дало бы u = 0 -- «отпустить мотор» ровно там, где надо
    толкать.  А это не экзотика: на стандартной карте вся строка ψ̇₀ = 0
    стартует именно оттуда (θ̇₀ = 0 тоже).

    Выбор: при v = 0 подаём u = u_max · sign(g).  Обоснование -- знак
    коэффициента при u в v̇.  Из §1.3

        v̇ = [ (α + γ + 2β cos ψ) u + … ] / Δ(ψ) ,

    и множитель α + γ + 2β cos ψ = (1, 1) M (1, 1)ᵀ > 0 для любой физичной
    матрицы масс.  Значит момент со знаком sign(g) немедленно уводит v в ту
    же сторону, произведение g·v становится положительным, и накачка
    начинается.  Остаётся один честный ноль: g = 0 (энергия уже на уровне) --
    там u = 0, и это то, что нужно: не добавлять и не отбирать.

    Чего закон НЕ обещает
    ---------------------
    * **E = E* не значит «на кривой в вертикаль».** Разложение точное (§4.2):

          E = H(ψ, ψ̇; 0)/γ + p_θ²/(2γ) ,   p_θ = β cos ψ · ψ̇ + γ θ̇ .

      При p_θ ≠ 0 тот же уровень E набирается при МЕНЬШЕЙ H: наклон получает
      энергии меньше, чем нужно, а остаток крутит колесо.  Сепаратрисное реле
      следит ровно за H и такой подмены не допускает по построению.  Поэтому
      энергия -- критерий НАКАЧКИ, а не критерий ПЕРЕДАЧИ: передача идёт по
      тому же `region`, что и раньше, а не по равенству энергий.
    * **Ни числа переключений, ни времени.** У сепаратрисного закона внутри
      множества восстановимости их 0 или 1 (замер ER-016).  Здесь знак u
      меняется всякий раз, когда меняет знак v, то есть на каждом взмахе.
    * **Оптимальности.** Сепаратрисный закон возвращает корпус откуда только
      можно (совпадение с аналитической границей на 1681 клетке из 1681);
      энергетический такого свойства не доказывает и не обязан.

    Параметры
    ---------
    Те же, что у `BangBangLQRController`, плюс `i_dtheta` -- индекс скорости
    колеса в состоянии (нужен, потому что в мощность входит θ̇, а
    сепаратрисному закону колесо не нужно вовсе).

    `u_max` здесь -- амплитуда накачки И предел, по которому построен регион;
    отдельного коэффициента k сознательно нет: он был бы второй переменной в
    опыте, который задуман как замена ровно одного закона.

    `system` должен уметь `energy(x)` и `E_upright` (`WheeledPendulum`).
    """

    def __init__(self, K, u_max, region, system, *, energy="total", i_psi=0,
                 i_theta=1, i_dpsi=2, i_dtheta=3, latch=True, wheel_ref=False,
                 K_final=None, final_region=None):
        if not hasattr(system, "E_upright"):
            raise TypeError(
                "EnergyBangBangController: модели нужен E_upright -- закон "
                "накачки определён через энергию (Key_Formulas §4)"
            )
        # Пара «величина + её мощность» берётся ЦЕЛИКОМ: гарантия закона стоит
        # ровно на том, что вторая есть производная первой.
        self.energy = energy
        self._value, self._rate_of = _energy_pair(system, energy)
        super().__init__(K, u_max, region, system, i_psi=i_psi, i_theta=i_theta,
                         i_dpsi=i_dpsi, latch=latch, wheel_ref=wheel_ref,
                         K_final=K_final, final_region=final_region)
        self.i_dtheta = int(i_dtheta)
        self.E_star = float(system.E_upright)

    def energy_gap(self, x_hat):
        """g = E* − E(x): сколько энергии НЕ ХВАТАЕТ до верхнего положения.

        Положительное -- качать, отрицательное -- тормозить.  Какая именно
        энергия -- решает `energy`; уровень цели `E* = D` у обеих один и тот
        же.  Вынесено ради теста: вдоль энергетической фазы |g| обязано не
        расти, и это проверка знака закона, а не сравнение с прошлым прогоном.
        """
        return self.E_star - self._value(np.asarray(x_hat, dtype=float))

    def drive_rate(self, x_hat):
        """r: множитель, на котором мотор делает работу, то есть dE/dt = u·r.

        Это ВТОРАЯ половина пары, и её нельзя выбрать отдельно от первой:

            energy="total" -> r = ψ̇ − θ̇          (мощность мотора, §4.1);
            energy="tilt"  -> r = b(ψ) ψ̇ / γ      (мощность в наклон, §4.3).

        У "tilt" скорости колеса нет вовсе -- в этом и вся разница.  Зато есть
        множитель b(ψ) = γ + β cos ψ, который МЕНЯЕТ ЗНАК на |ψ| = 1.929 рад
        (параметры по умолчанию), то есть внутри стандартной карты: за этим
        наклоном тот же момент качает наклон в другую сторону.  Поэтому знак
        берётся у всего произведения, а не у одной скорости -- иначе закон за
        этой границей работал бы наоборот.
        """
        x = np.asarray(x_hat, dtype=float)
        if self.energy == "total":
            return x[..., self.i_dpsi] - x[..., self.i_dtheta]
        return self._rate_of(x, 1.0)

    #: Прежнее имя `drive_rate` для energy="total". Оставлено, потому что так
    #: называется величина в §4.1 и в тестах, написанных до появления "tilt".
    relative_rate = drive_rate

    def first_phase_action(self, x):
        """u = u_max · sign(g) · sign(r), с sign(r)|_{r=0} := +1.

        Разбор вырождения r = 0 -- в докстринге класса.  Возвращается форма
        (..., 1), как у базового класса: соглашение о пачках (A8).
        """
        gap = np.asarray(self.energy_gap(x), dtype=float)
        rate = np.asarray(self.drive_rate(x), dtype=float)
        direction = np.where(rate != 0.0, np.sign(rate), 1.0)
        return (self.u_max * np.sign(gap) * direction)[..., None]


class TrajectoryTrackingController(Controller):
    """Слежение за заранее рассчитанной траекторией: ЛКР, меняющийся во времени.

        k = round((t - t0) / dt),
        u = u_bar_k - K_k (x_hat - x_bar_k).

    Откуда числа. `wpend.ddp.ilqr` один раз до прогона считает номинальную
    траекторию (x_bar, u_bar) и матрицы K_k. Синтеза здесь нет, как и у
    `LinearFeedbackController`: регулятор только исполняет план.

    Зачем обратная связь, если план оптимален. Без неё (u = u_bar_k) это
    разомкнутое управление: любое отклонение -- другой x0, шум, неточная
    модель -- растёт вдоль неустойчивой траектории маятника. K_k -- это
    линеаризация оптимального закона вокруг плана: оно говорит, как исправлять
    отклонение δx на шаге k. Это та же K, что в обратном проходе iLQR
    (Tassa, Erez & Todorov, IROS 2012, §II; Tedrake, *Underactuated Robotics*,
    глава про LQR-слежение за траекторией).

    Что происходит за горизонтом. Шаг k обрезается до N-1, и используется
    последняя точка плана x_bar_N. Закон тогда постоянный:
    u = -K_{N-1} x + (u_bar_{N-1} + K_{N-1} x_bar_N). Если цель плана --
    ноль, а Q_f = P из `lqr()`, то конец плана уже живёт в режиме ЛКР,
    u_bar_{N-1} ≈ -K_{N-1} x_bar_N, скобка ≈ 0, и регулятор превращается в
    обычный ЛКР с K_{N-1} ≈ K. Замер (psi0 = 0.3, план 3 с, dt = 0.01):
    скобка ≈ 0.004 Н·м, к 9 с |psi| ≈ 1e-4. Для других целей это не
    гарантировано, и прогон длиннее плана -- отдельный вопрос.

    Время. Индекс считается из t, а не счётчиком вызовов: так регулятор не
    хранит памяти, и `reset()` ему не нужен. `rollout` даёт t = t0 + k·dt
    точно (формулой, без накопления), поэтому round безопасен. dt регулятора
    ОБЯЗАН совпадать с dt прогона: иначе план исполняется в другом темпе.

    Пачка (M, n) поддерживается: t общее для всех строк, поэтому k одно и то
    же, а x_hat - x_bar_k транслируется по строкам.

    Параметры
    ---------
    x_bar : (N+1, n)
    u_bar : (N, m)
    K : (N, m, n)
    dt : float
    t0 : float
        Момент, которому соответствует x_bar_0.
    """

    def __init__(self, x_bar, u_bar, K, dt, t0=0.0):
        self.x_bar = np.asarray(x_bar, dtype=float)
        self.u_bar = np.asarray(u_bar, dtype=float)
        self.K = np.asarray(K, dtype=float)
        self.dt = float(dt)
        self.t0 = float(t0)
        n_steps = self.u_bar.shape[0]
        if self.x_bar.shape[0] != n_steps + 1 or self.K.shape[0] != n_steps:
            raise ValueError(
                f"форма плана не согласована: x_bar {self.x_bar.shape}, "
                f"u_bar {self.u_bar.shape}, K {self.K.shape} -- нужно "
                "(N+1, n), (N, m), (N, m, n)")

    def act(self, t: float, x_hat: np.ndarray) -> np.ndarray:
        x = np.asarray(x_hat, dtype=float)
        n_steps = self.u_bar.shape[0]
        k = int(round((t - self.t0) / self.dt))
        k_u = min(max(k, 0), n_steps - 1)
        k_x = min(max(k, 0), n_steps)       # за горизонтом держим x_bar_N
        error = x - self.x_bar[k_x]
        return self.u_bar[k_u] - error @ self.K[k_u].T


class MPCController(Controller):
    """Управление с прогнозирующей моделью (MPC) на основе `wpend.ddp.ilqr`.

    Раз в такт управления dt_plan регулятор:
      1. берёт текущую оценку x_hat как начальное состояние;
      2. решает задачу iLQR на горизонте N шагов dt_plan по СВОЕЙ модели,
         начиная с прошлого плана, сдвинутого на шаг (тёплый старт);
      3. прикладывает первое управление плана u_bar_0 и держит его до
         следующего такта (zero-order hold).
    Остальной план выбрасывается; от него остаётся только тёплый старт.

    Где здесь обратная связь. Явной матрицы K в законе нет: обратная связь --
    это само перепланирование из измеренного состояния. На линейной системе с
    квадратичной ценой это можно проверить точно: решение задачи из любого x
    -- линейная функция u = -K_0 x, и MPC обязан совпасть с этой постоянной
    обратной связью (`tests/test_mpc.py`).

    Почему это законно в пяти слоях
    -------------------------------
    * Память (прошлый план, момент следующего такта, удерживаемое u) живёт
      в регуляторе -- правило 2. `reset()` её стирает.
    * Модель внутри регулятора -- это модель РЕГУЛЯТОРА, а не мир: `rollout`
      по-прежнему двигает истинную систему. Их можно намеренно сделать
      разными (другая масса, другой интегратор) -- опыт «MPC с неточной
      моделью» получается подменой аргумента.
    * Правило 5 (один dt) не нарушено: rollout зовёт `act` каждый шаг, а
      регулятор сам решает, что между тактами управление не меняется. dt_plan
      должен быть кратен dt прогона, иначе такт «плывёт» относительно сетки
      прогона (такт срабатывает на первом шаге, где t >= t_next). Честное
      разделение dt_control / dt_sim -- по-прежнему PROPOSALS.md §B2.
    * Предел момента планировщик берёт из СВОЕЙ модели: `model.u_bounds`.
      Модель с `u_max` -- планирование с пределом (box-DDP, `wpend/ddp.py`),
      план допустим, и `System.clip_action` мира его не меняет. Модель без
      предела -- прежний опыт «планировщик не знает, мир обрезает».

    Устойчивость. Терминальная цена Q_f = P из `lqr()` -- классическое
    условие устойчивости MPC: хвост за горизонтом оценён ценой ЛКР, который
    доведёт систему до нуля (Rawlings, Mayne & Diehl, *Model Predictive
    Control*, 2-е изд., гл. 2). Строго это доказано для точного решения и
    терминального множества; здесь ни того, ни другого нет, так что это
    ориентир, а не сертификат.

    Параметры
    ---------
    model, integrator
        Модель планировщика (обычно та же система, что в прогоне).
    dt_plan : float
        Шаг плана и такт перепланирования.
    horizon : int
        N -- число шагов плана. Горизонт в секундах -- N·dt_plan.
    Q, R, Q_f
        Веса цены, как в `ilqr`.
    x_goal : (n,) | None
    n_iter : int
        Итераций iLQR на такт. Тёплый старт уже почти оптимален, поэтому
        хватает 1-2 (Tassa, Erez & Todorov, IROS 2012, §III).
    first_iter : int
        Итераций на ПЕРВОМ такте, где тёплого старта ещё нет.
    K_init : (m, n) | None
        Как получить начальное приближение на первом такте: прогон модели
        под u = -K_init x. None -- нули. Для неустойчивой системы нули плохи:
        прогон падает, и iLQR застревает в локальном минимуме (замер в
        `tests/test_ddp.py`: цена 3653 против 84.1).
    record_plans : bool
        Писать в `self.plans` каждый план (t, x_bar, u_bar, итерации, время
        расчёта). Только для просмотра поведения; на управление не влияет.
    mu : float
        Регуляризация Q_uu в iLQR (см. `ilqr`). Она сдвигает не только шаг, но
        и матрицы G: на линейной задаче при mu = 1e-6 управление отличается от
        точного на 4e-5 относительно (Q_uu ≈ 0.05). Для прогонов это шум, для
        точного оракула в тестах ставится mu = 0.

    Пачка (M, n): каждая строка -- независимая задача со своим планом; цена
    растёт в M раз. Для сетки начальных условий это самая дорогая вещь в
    проекте, окно так её вызывать не должно.
    """

    def __init__(self, model, integrator, dt_plan, horizon, Q, R, Q_f, *,
                 x_goal=None, n_iter=2, first_iter=50, K_init=None, mu=1e-6,
                 record_plans=False):
        self.model = model
        self.integrator = integrator
        self.dt_plan = float(dt_plan)
        self.horizon = int(horizon)
        self.Q, self.R, self.Q_f = Q, R, Q_f
        self.x_goal = x_goal
        self.n_iter = int(n_iter)
        self.first_iter = int(first_iter)
        self.K_init = None if K_init is None else np.atleast_2d(
            np.asarray(K_init, dtype=float))
        self.mu = float(mu)
        self.record_plans = bool(record_plans)
        self.reset()

    def reset(self) -> None:
        self._plans = None        # (M, N, m): u_bar последнего плана по строкам
        self._u_hold = None       # (M, m): управление, которое держим до такта
        self._t_next = None       # момент следующего перепланирования
        self.n_replans = 0        # счётчик для замеров
        # Журнал планов (record_plans=True): что регулятор ПРЕДСКАЗЫВАЛ на каждом
        # такте. Нужен окну, которое показывает поведение алгоритма; для
        # пачки пишется только строка 0, иначе память росла бы в M раз.
        self.plans = []

    def _initial_guess(self, x0):
        """Прогон модели под u = -K_init x -- начальное приближение."""
        m = self.model.n_action
        u = np.zeros((self.horizon, m))
        if self.K_init is None:
            return u
        x = np.array(x0, dtype=float)
        for k in range(self.horizon):
            # clip_action модели: если модель знает предел, начальный план
            # стартует допустимым -- это ЛКР с насыщением, а не без него.
            u[k] = self.model.clip_action(-self.K_init @ x)
            x = self.integrator.step(self.model.f, k * self.dt_plan, x, u[k],
                                     self.dt_plan)
        return u

    def _replan(self, t, x_row, i):
        from .ddp import ilqr     # отложенный импорт: ddp -- не слой, см. модуль

        if self._plans[i] is None:
            u_init, max_iter = self._initial_guess(x_row), self.first_iter
        else:
            # Тёплый старт: план сдвигается на шаг, последнее управление
            # повторяется. На конце плана система уже в режиме ЛКР, поэтому
            # повтор -- разумное продолжение.
            prev = self._plans[i]
            u_init = np.concatenate([prev[1:], prev[-1:]], axis=0)
            max_iter = self.n_iter
        t_wall = time.perf_counter()
        x_bar, u_bar, _, costs = ilqr(self.model, self.integrator, x_row, self.dt_plan,
                                      self.horizon, self.Q, self.R, self.Q_f,
                                      x_goal=self.x_goal, u_init=u_init, t0=t,
                                      max_iter=max_iter, mu=self.mu,
                                      u_bounds=self.model.u_bounds)
        if self.record_plans and i == 0:
            self.plans.append(dict(t=t, x=x_bar, u=u_bar[:, 0], iters=len(costs) - 1,
                                   wall=time.perf_counter() - t_wall))
        self._plans[i] = u_bar
        return u_bar[0]

    def act(self, t: float, x_hat: np.ndarray) -> np.ndarray:
        x = np.asarray(x_hat, dtype=float)
        rows = x.reshape(-1, x.shape[-1])
        M = rows.shape[0]
        if self._plans is None or len(self._plans) != M:
            self._plans = [None] * M
            self._u_hold = np.zeros((M, self.model.n_action))
            self._t_next = None

        # 1e-9 -- допуск на округление: t приходит как t0 + k·dt, а t_next
        # копится суммой, и точное равенство может не выполниться.
        if self._t_next is None or t >= self._t_next - 1e-9:
            for i in range(M):
                self._u_hold[i] = self._replan(t, rows[i], i)
            self.n_replans += 1
            base = t if self._t_next is None else self._t_next
            self._t_next = base + self.dt_plan
        return self._u_hold.reshape(x.shape[:-1] + (self.model.n_action,)).copy()
